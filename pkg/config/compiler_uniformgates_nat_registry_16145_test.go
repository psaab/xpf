// #16145 W2.1 NAT-first gate registry tests.
//
// These tests are the decisive acceptance check for the NAT sub-run
// conversion, behind the merged #16166 PR-0 census:
//
//   - order census: the registry slice order IS the censused execution
//     order; reordering, inserting, or dropping an entry fails here, so
//     the strict first-error slot (invariant #6) and the tolerant
//     warning-accumulation order (invariant #7) cannot drift silently.
//   - per-gate fail-on-revert: every one of the 20 registry entries is
//     driven directly with a config that trips it, in strict and
//     tolerant modes; gutting an entry's validator call turns that
//     gate's subtest RED — the fourth-link wiring proof PR-0
//     deliberately does not claim (B-codex dissent on #16166:
//     reflection checks the flag, not that a guard reads it). No gate
//     is exempted onto a dedicated suite.
//   - strict/lenient x generic/node matrix: a config tripping two NAT
//     gates reports the earlier gate's error on every strict cell and
//     both warnings, in registry order, on every lenient cell.
//   - structured Diagnostic additive, prose retained: cfg.Diagnostics
//     mirrors the warnings the registry gates append, with gate
//     attribution, while the warning strings stay byte-identical.
//
// The 6-fixture golden (TestCompileGolden4406) remains the necessary-
// not-sufficient byte proof; it is NOT regenerated by this change (the
// issue stop-rule: a baseline regen aborts the refactor). Its baseline
// fails identically before and after this change on current master;
// the PR records the differential (byte-identical actual output).

// natGateOrderCensus16145 is the censused NAT gate execution order.
// It reproduces, in order, the hand-written gate sequence that
// runUniformGatesNAT executed before the registry: destination-NAT
// address, match-address literals, DNAT protocol, match destination
// port, unknown match leaves, unconstrained match, DNAT pool, the two
// pool unknown-leaf gates, deterministic, source pool port-range,
// pool address-range, pool references, rule persistent-NAT, pool
// address scope, pool address grammar, pool family (#16600), aggregate
// cardinality, the DNAT off-shadow gate, and the mapped/compat gate
// (#16875, appended last so older first-error slots are unchanged).
// appendDNATOffShadowPotentialWarnings is not a gate (warning-only, no
// strict error) and stays outside the census.
var natGateOrderCensus16145 = []string{
	"destNATAddresses",
	"natMatchAddressLiterals",
	"destNATProtocol",
	"natMatchDestinationPort",
	"natUnknownMatchLeaves",
	"natRuleMatchConstrained",
	"dnatPool",
	"destinationNATPoolUnknownLeaves",
	"sourceNATPoolUnknownLeaves",
	"sourceNATDeterministic",
	"sourceNATPool",
	"natPoolAddressRange",
	"natPoolReferences",
	"sourceNATRulePersistentNAT",
	"sourceNATPoolAddressScope",
	"sourceNATPoolAddressGrammar",
	"sourceNATPoolFamily",
	"sourceNATAggregateCardinality",
	"dnatOffShadow",
	"natMappedCompat",
}

// TestNATGateRegistryOrderCensus16145 pins the registry slice to the
// censused order above. Fail-on-revert: swap, insert, or delete any
// entry in natGates and this test fails, naming the first divergence.
func TestNATGateRegistryOrderCensus16145(t *testing.T) {
	if len(natGates) != len(natGateOrderCensus16145) {
		t.Fatalf("natGates has %d entries, census has %d: a gate was added or dropped without a deliberate census update",
			len(natGates), len(natGateOrderCensus16145))
	}
	seen := make(map[string]bool, len(natGates))
	for i, g := range natGates {
		if g.name != natGateOrderCensus16145[i] {
			t.Errorf("natGates[%d] = %q, census order wants %q: gate order is observable (strict first-error, tolerant warning order) and must not drift",
				i, g.name, natGateOrderCensus16145[i])
		}
		if g.name == "" {
			t.Errorf("natGates[%d] has an empty name; Diagnostic attribution requires it", i)
		}
		if seen[g.name] {
			t.Errorf("natGates[%d] duplicates gate name %q", i, g.name)
		}
		seen[g.name] = true
		if g.lenient == nil {
			t.Errorf("gate %q has a nil lenient accessor; the runner would panic", g.name)
		}
		if g.run == nil {
			t.Errorf("gate %q has a nil run func; the registry would silently skip it", g.name)
		}
	}
}

// natGateByName16145 returns the registry entry with the given census
// name, failing the test if the registry lost it.
func natGateByName16145(t *testing.T, name string) natGate {
	t.Helper()
	for _, g := range natGates {
		if g.name == name {
			return g
		}
	}
	t.Fatalf("registry has no gate named %q; the census entry was dropped", name)
	return natGate{}
}

