package dataplane

// #4977: source→object freshness gate for the git-tracked
// userspace_xdp_bpfel.o embedded by userspace_xdp_rust.go.
//
// `make build` is a plain `go build` and by design never runs `make
// generate`; `make test` never rebuilds the shim. So a logic-only edit
// to userspace-xdp/** source (a packet-steering or security fix) that
// is NOT followed by `make generate` + committing the regenerated .o
// would ship the STALE embedded object while source review and `make
// test` stay green. The existing canaries only bind program/map
// allowlists, max_entries sizing (validateUserspaceShimSpec), and a
// `go generate -n` dry-run — none proves the tracked object corresponds
// to CURRENT source.
//
// This manifest records a deterministic SHA-256 of every
// freshness-relevant shim build input AND of the tracked object itself.
// TestUserspaceXDPShimObjectMatchesSourceManifest recomputes both from
// the working tree and fails when they drift, telling the operator to
// run `make generate`. The manifest is regenerated ONLY by
// build-userspace-xdp.sh (via cmd/shim-manifest), immediately after the
// verifier-gated install of the object, so it stays in lockstep with
// the object it describes — the manifest can never record a source hash
// newer than the object that source produced.

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/psaab/xpf/pkg/fsatomic"
)

const (
	// UserspaceXDPManifestRelPath is the repo-relative path to the
	// committed freshness manifest.
	UserspaceXDPManifestRelPath = "pkg/dataplane/userspace_xdp_manifest.json"

	// UserspaceXDPGateVerdictRelPath is the repo-relative verifier
	// attestation written by build-userspace-xdp.sh next to the tracked
	// object whenever an object is verifier-gated and installed (#10909).
	UserspaceXDPGateVerdictRelPath = "pkg/dataplane/userspace_xdp_gate_verdict.json"

	// userspaceXDPObjectRelPath is the tracked shim object embedded by
	// userspace_xdp_rust.go (`//go:embed userspace_xdp_bpfel.o`).
	userspaceXDPObjectRelPath = "pkg/dataplane/userspace_xdp_bpfel.o"
	// ShimPinnedBPFLinkerVersion is the bpf-linker pin the build recipe
	// enforces (PINNED_BPF_LINKER_VERSION in build-userspace-xdp.sh).
	// Recorded in the gate verdict's provenance (#15218); both consumer
	// gates compare against this value so a linker drift cannot be
	// laundered into an adopted build digest.
	ShimPinnedBPFLinkerVersion = "0.10.2"

	// userspaceXDPSourceDir holds the Rust sources compiled into the
	// shim. Every *.rs beneath it (recursively) is a freshness input, so
	// adding a new module file is caught by the manifest gate. Scoped to
	// src/ only so cargo's target/ build artifacts are never walked.
	userspaceXDPSourceDir = "userspace-xdp/src"

	userspaceXDPManifestComment = "GENERATED by `make generate` " +
		"(pkg/dataplane/build-userspace-xdp.sh via cmd/shim-manifest) — DO NOT EDIT BY HAND. " +
		"A TestUserspaceXDPShimObjectMatchesSourceManifest mismatch means " +
		"pkg/dataplane/userspace_xdp_bpfel.o is stale versus userspace-xdp/** source; " +
		"run `make generate`. See pkg/dataplane/README.md (#4977)."
)

// userspaceXDPFixedFreshnessInputs are the non-.rs build inputs that
// determine the shim object's bytes: the Cargo manifest + locked
// dependency graph, the pinned Rust toolchain, BOTH the crate-local and
// the repo-root cargo config (cargo loads ancestor configs too, so a
// root-level BPF-target rustflags edit could change the .o — currently
// inert x86_64, hashed for completeness), the build recipe itself
// (build-userspace-xdp.sh embeds the bpf-linker version pin and threads
// MAX_INTERFACES), and bpf/headers/xpf_common.h (whose MAX_INTERFACES
// #define is awk-extracted by the recipe and sizes the shim's binding
// array + maps). Paths are repo-relative POSIX.
//
// xpf_common.h is hashed directly here so the freshness gate is
// self-sufficient: the header->Go max_entries parity canary
// (TestMaxInterfacesMatchesCHeader) t.Skips when the header is absent, so
// leaning on it alone left a fail-open hole. Whole-file hashing trades a
// little churn on unrelated header edits for a fail-closed gate.
//
// Deliberately EXCLUDED: userspace-xdp/.gitignore (not a build input) and
// cargo's target/ tree (build artifacts, untracked).
var userspaceXDPFixedFreshnessInputs = []string{
	".cargo/config.toml",
	"bpf/headers/xpf_common.h",
	"pkg/dataplane/build-userspace-xdp.sh",
	"userspace-xdp/.cargo/config.toml",
	"userspace-xdp/Cargo.lock",
	"userspace-xdp/Cargo.toml",
	"userspace-xdp/rust-toolchain.toml",
}

type shimManifestEntry struct {
	Path   string `json:"path"`
	SHA256 string `json:"sha256"`
}

type shimFreshnessManifest struct {
	Comment string            `json:"_comment"`
	Object  shimManifestEntry `json:"object"`
	// BuildDigest is SHA-256 over the sorted freshness inputs in
	// canonical "path<TAB>sha256<LF>" form, below. It is emitted only
	// when Compute has been shown the verifier gate verdict attesting
	// that this object was built and installed (#13963); empty means
	// no such attestation, which the freshness test treats as stale.
	BuildDigest string `json:"build_digest,omitempty"`
	// ShimFacts are the object's SELF-REPORTED compile-time values
	// (#4555), read back out of the object via ReadShimFactsFromObject
	// rather than modelled from the shim's source. Recording them here
	// makes them travel with the artifact: a consumer of a prebuilt
	// object (the Debian packaging path never compiles the shim crate)
	// checks the same numbers the generator measured.
	ShimFacts *ShimFacts          `json:"shim_facts"`
	Inputs    []shimManifestEntry `json:"inputs"`
}

// userspaceXDPBuildDigest is the source digest the verifier gate
// verdict attests, in canonical form: for every freshness input in
// sorted order, its repo-relative path, a TAB, its lowercase hex
// SHA-256 and a LF. Recorded in the verdict as a single SHA-256 over
// that stream, so the freshness test can recognise a manifest that a
// hand-run of cmd/shim-manifest re-stamped without a rebuild.
func userspaceXDPBuildDigest(entries []shimManifestEntry) string {
	h := sha256.New()
	for _, e := range entries {
		fmt.Fprintf(h, "%s\t%s\n", e.Path, e.SHA256)
	}
	return hex.EncodeToString(h.Sum(nil))
}

// userspaceXDPGateVerdictProvenance is the build provenance the
// recipe records through shimverify (#15218): the toolchain cargo
// actually ran, whether it was the pin, the bpf-linker version, and
// a digest of the codegen environment.
type userspaceXDPGateVerdictProvenance struct {
	Toolchain        string `json:"toolchain"`
	Pinned           bool   `json:"pinned"`
	BPFLinker        string `json:"bpf_linker"`
	CodegenEnvDigest string `json:"codegen_env_digest"`
}

// userspaceXDPGateVerdict is the subset of the #10909 gate-verdict
// sidecar the freshness gate consumes: the object the verifier gated
// and, from #13963, the build digest its build was gated under, plus
// from #15218 the provenance that build ran under.
type userspaceXDPGateVerdict struct {
	ObjectSHA256 string                             `json:"object_sha256"`
	BuildDigest  string                             `json:"build_digest"`
	Provenance   *userspaceXDPGateVerdictProvenance `json:"provenance"`
}

func readUserspaceXDPGateVerdict(repoRoot string) (*userspaceXDPGateVerdict, error) {
	b, err := os.ReadFile(filepath.Join(repoRoot, filepath.FromSlash(UserspaceXDPGateVerdictRelPath)))
	if err != nil {
		return nil, err
	}
	var v userspaceXDPGateVerdict
	if err := json.Unmarshal(b, &v); err != nil {
		return nil, fmt.Errorf("parse %s: %w", UserspaceXDPGateVerdictRelPath, err)
	}
	return &v, nil
}

// ShimCodegenEnvDigest is SHA-256 over the canonical codegen-env
// stream "RUSTFLAGS=<v>\nCARGO_ENCODED_RUSTFLAGS=<v>\n" (#15218).
// These two variables are the rustc-codegen inputs cargo honours from
// the ambient environment; everything else that can steer codegen
// for the bpfel target lives in hashed files (.cargo/config.toml,
// Cargo.toml, the build recipe).
func ShimCodegenEnvDigest(rustflags, encoded string) string {
	sum := sha256.Sum256([]byte("RUSTFLAGS=" + rustflags + "\nCARGO_ENCODED_RUSTFLAGS=" + encoded + "\n"))
	return hex.EncodeToString(sum[:])
}

// WellKnownCodegenEnvDigest is ShimCodegenEnvDigest("",""): the only
// codegen environment a gated build may have, because
// build-userspace-xdp.sh scrubs both variables before running cargo.
func WellKnownCodegenEnvDigest() string { return ShimCodegenEnvDigest("", "") }

// pinnedShimToolchain extracts the pinned channel from
// rust-toolchain.toml with the same strictness as the build recipe:
// exactly one channel key in the [toolchain] table, formatted
// nightly-YYYY-MM-DD. Any drift fails closed.
func pinnedShimToolchain(path string) (string, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	inToolchain := false
	var channels []string
	for _, line := range strings.Split(string(b), "\n") {
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, "[") {
			inToolchain = trimmed == "[toolchain]"
			continue
		}
		if !inToolchain {
			continue
		}
		key, value, ok := strings.Cut(trimmed, "=")
		if !ok || strings.TrimSpace(key) != "channel" {
			continue
		}
		if i := strings.Index(value, "#"); i >= 0 {
			value = value[:i]
		}
		channels = append(channels, strings.Trim(strings.TrimSpace(value), `"'`))
	}
	if len(channels) != 1 || channels[0] == "" {
		return "", fmt.Errorf("expected exactly one channel in [toolchain] of %s, got %v", path, channels)
	}
	c := channels[0]
	if len(c) != len("nightly-2006-01-02") || !strings.HasPrefix(c, "nightly-") {
		return "", fmt.Errorf("toolchain channel %q in %s is not a nightly-YYYY-MM-DD pin", c, path)
	}
	for _, r := range c[len("nightly-"):] {
		if (r < '0' || r > '9') && r != '-' {
			return "", fmt.Errorf("toolchain channel %q in %s is not a nightly-YYYY-MM-DD pin", c, path)
		}
	}
	return c, nil
}

// verdictProvenanceClean reports whether a gate verdict's recorded
// provenance (#15218) proves a pinned build under the scrubbed
// codegen env with the pinned bpf-linker. Anything else — absent
// provenance, unpinned, wrong toolchain/linker, foreign env digest —
// is not provenance a consumer gate may trust.
func verdictProvenanceClean(repoRoot string, v *userspaceXDPGateVerdict) bool {
	p := v.Provenance
	if p == nil || !p.Pinned {
		return false
	}
	pin, err := pinnedShimToolchain(filepath.Join(repoRoot, "userspace-xdp", "rust-toolchain.toml"))
	if err != nil || p.Toolchain != pin {
		return false
	}
	return p.BPFLinker == ShimPinnedBPFLinkerVersion && p.CodegenEnvDigest == WellKnownCodegenEnvDigest()
}

// UserspaceXDPBuildDigest returns the canonical digest of all source and
// toolchain inputs that produce the embedded shim object.
func UserspaceXDPBuildDigest(repoRoot string) (string, error) {
	paths, err := userspaceXDPFreshnessInputPaths(repoRoot)
	if err != nil {
		return "", err
	}
	entries, err := hashUserspaceXDPInputs(repoRoot, paths)
	if err != nil {
		return "", err
	}
	return userspaceXDPBuildDigest(entries), nil
}

// userspaceXDPFreshnessInputPaths returns the sorted, repo-relative set
// of freshness-relevant shim build inputs: the fixed set above plus
// every *.rs under userspace-xdp/src. It errors if any fixed input is
// missing so an input can never be silently dropped from the manifest.
func userspaceXDPFreshnessInputPaths(repoRoot string) ([]string, error) {
	paths := make([]string, 0, len(userspaceXDPFixedFreshnessInputs)+4)
	for _, rel := range userspaceXDPFixedFreshnessInputs {
		abs := filepath.Join(repoRoot, filepath.FromSlash(rel))
		if _, err := os.Stat(abs); err != nil {
			return nil, fmt.Errorf("freshness input %q: %w", rel, err)
		}
		paths = append(paths, rel)
	}

	srcRoot := filepath.Join(repoRoot, filepath.FromSlash(userspaceXDPSourceDir))
	walkErr := filepath.WalkDir(srcRoot, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() || !strings.HasSuffix(d.Name(), ".rs") {
			return nil
		}
		rel, err := filepath.Rel(repoRoot, p)
		if err != nil {
			return err
		}
		paths = append(paths, filepath.ToSlash(rel))
		return nil
	})
	if walkErr != nil {
		return nil, fmt.Errorf("walk %s: %w", userspaceXDPSourceDir, walkErr)
	}

	sort.Strings(paths)
	return paths, nil
}

func sha256File(path string) (string, error) {
	f, err := os.Open(path)
	if err != nil {
		return "", err
	}
	defer f.Close()

	h := sha256.New()
	if _, err := io.Copy(h, f); err != nil {
		return "", err
	}
	return hex.EncodeToString(h.Sum(nil)), nil
}

// ComputeUserspaceXDPManifest builds the freshness manifest from the
// working tree rooted at repoRoot (repo-relative paths).
func ComputeUserspaceXDPManifest(repoRoot string) (*shimFreshnessManifest, error) {
	objAbs := filepath.Join(repoRoot, filepath.FromSlash(userspaceXDPObjectRelPath))
	objHash, err := sha256File(objAbs)
	if err != nil {
		return nil, fmt.Errorf("hash shim object %q: %w", userspaceXDPObjectRelPath, err)
	}

	inputs, err := userspaceXDPFreshnessInputPaths(repoRoot)
	if err != nil {
		return nil, err
	}
	entries, err := hashUserspaceXDPInputs(repoRoot, inputs)
	if err != nil {
		return nil, err
	}

	facts, err := ReadShimFactsFromObject(objAbs)
	if err != nil {
		return nil, fmt.Errorf("read emitted shim facts (#4555): %w", err)
	}

	manifest := &shimFreshnessManifest{
		Comment:   userspaceXDPManifestComment,
		Object:    shimManifestEntry{Path: userspaceXDPObjectRelPath, SHA256: objHash},
		ShimFacts: facts,
		Inputs:    entries,
	}
	verdict, err := readUserspaceXDPGateVerdict(repoRoot)
	if err == nil && verdict.ObjectSHA256 == objHash && verdict.BuildDigest == userspaceXDPBuildDigest(entries) && verdictProvenanceClean(repoRoot, verdict) {
		manifest.BuildDigest = verdict.BuildDigest
	}
	return manifest, nil
}

func hashUserspaceXDPInputs(repoRoot string, paths []string) ([]shimManifestEntry, error) {
	entries := make([]shimManifestEntry, 0, len(paths))
	for _, rel := range paths {
		h, err := sha256File(filepath.Join(repoRoot, filepath.FromSlash(rel)))
		if err != nil {
			return nil, fmt.Errorf("hash input %q: %w", rel, err)
		}
		entries = append(entries, shimManifestEntry{Path: rel, SHA256: h})
	}
	return entries, nil
}

// MarshalUserspaceXDPManifest renders the manifest deterministically as
// indented JSON with a trailing newline. Struct field order and sorted
// input entries make the output stable, so a regenerated manifest yields
// a clean git diff when nothing changed.
func MarshalUserspaceXDPManifest(m *shimFreshnessManifest) ([]byte, error) {
	b, err := json.MarshalIndent(m, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(b, '\n'), nil
}

func parseUserspaceXDPManifest(b []byte) (*shimFreshnessManifest, error) {
	var m shimFreshnessManifest
	if err := json.Unmarshal(b, &m); err != nil {
		return nil, err
	}
	return &m, nil
}

// WriteUserspaceXDPManifest recomputes and writes the manifest to
// repoRoot/UserspaceXDPManifestRelPath. It is invoked by
// build-userspace-xdp.sh (through cmd/shim-manifest) right after the
// verifier-gated install of the shim object.
func WriteUserspaceXDPManifest(repoRoot string) error {
	m, err := ComputeUserspaceXDPManifest(repoRoot)
	if err != nil {
		return err
	}
	b, err := MarshalUserspaceXDPManifest(m)
	if err != nil {
		return err
	}
	out := filepath.Join(repoRoot, filepath.FromSlash(UserspaceXDPManifestRelPath))
	// Atomic write (pkg/fsatomic) rather than os.WriteFile: the project's
	// TestNoDirectOsWriteFile canary forbids raw os.WriteFile in pkg/, and a
	// torn manifest (partial write on a crash mid-generate) would fail the
	// freshness test with a corrupt-file error rather than a clean stale
	// signal. temp-then-rename keeps the committed manifest always intact.
	return fsatomic.WriteFileAtomic(out, b, 0o644)
}
