// TestFactoryResetRestoresIdentityAfterFailedWipe10769 is the d05-F6 hostname
// recovery proof: the wipe overwrites the identity files (the seal leg) and a
// LATER leg fails. The failed reset must restore every snapshotted file
// byte-for-byte even though the kernel name already equals the configured
// name — the trap that made the old applyHostname recovery return early and
// leave xpf on disk.
func TestFactoryResetRestoresIdentityAfterFailedWipe10769(t *testing.T) {
	isolateFactoryResetOwnershipPaths(t)
	isolateFactoryResetIdentityPaths(t)
	isolateHandoffFlag(t)
	dir := t.TempDir()
	store, err := configstore.New(filepath.Join(dir, "xpf.conf"))
	if err != nil {
		t.Fatal(err)
	}
	if err := store.EnterConfigure(); err != nil {
		t.Fatal(err)
	}
	if _, err := store.LoadSet("set system host-name tenant-fw\n"); err != nil {
		t.Fatalf("LoadSet: %v", err)
	}
	if _, err := store.Commit(); err != nil {
		t.Fatalf("Commit: %v", err)
	}
	restoreHost := osHostname
	osHostname = func() (string, error) { return "tenant-fw", nil }
	t.Cleanup(func() { osHostname = restoreHost })

	want := map[string]string{
		hostnamePath:        "tenant-fw\n",
		resetHostsPath:      "127.0.0.1 localhost\n127.0.1.1 tenant-fw\n",
		resetResolvConfPath: "# Generated by xpfd — do not edit\nnameserver 192.0.2.53\n",
		resetKnownHostsPath: "# Managed by xpfd — do not edit\nold.example ssh-ed25519 AAAA\n",
	}
	for path, body := range want {
		if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	d := &Daemon{applySem: semaphore.NewWeighted(1), store: store}
	wipeErr := errors.New("rendered-config leg failed")
	if err := d.factoryReset(context.Background(), func() error {
		for path := range want {
			if err := os.WriteFile(path, []byte("wiped\n"), 0o600); err != nil {
				t.Fatalf("simulate seal overwrite: %v", err)
			}
		}
		return wipeErr
	}); !errors.Is(err, wipeErr) {
		t.Fatalf("factoryReset error = %v, want %v", err, wipeErr)
	}
	for path, body := range want {
		got, err := os.ReadFile(path)
		if err != nil || string(got) != body {
			t.Errorf("identity file %s = %q, want pre-wipe %q (err=%v)", path, got, body, err)
		}
	}
}

// TestFactoryResetSurfacesIdentityRestoreFailure10769 pins that a failed
// identity restore is surfaced, not swallowed: the wipe breaks one restore
// target (replacing the file with a directory) and fails, so the reset error
// must name both the wipe failure and the restore failure.
func TestFactoryResetSurfacesIdentityRestoreFailure10769(t *testing.T) {
	isolateFactoryResetOwnershipPaths(t)
	isolateFactoryResetIdentityPaths(t)
	isolateHandoffFlag(t)
	if err := os.MkdirAll(filepath.Dir(resetHostsPath), 0o700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(resetHostsPath, []byte("127.0.0.1 localhost\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	d := &Daemon{applySem: semaphore.NewWeighted(1)}
	wipeErr := errors.New("wipe failed")
	err := d.factoryReset(context.Background(), func() error {
		if err := os.Remove(resetHostsPath); err != nil {
			t.Fatalf("break restore target: %v", err)
		}
		if err := os.MkdirAll(resetHostsPath, 0o700); err != nil {
			t.Fatalf("break restore target: %v", err)
		}
		return wipeErr
	})
	if !errors.Is(err, wipeErr) {
		t.Fatalf("factoryReset error = %v, want %v", err, wipeErr)
	}
	if err == nil || !strings.Contains(err.Error(), "restore") {
		t.Fatalf("factoryReset error must surface the identity restore failure, got %v", err)
	}
}

// TestFactoryResetFailsWhenKeaLeasesReappear10769 pins the post-wipe lease
// re-verification: a wipe that reports success while a lease file is present
// (a writer racing the unlink) must fail the reset closed. The reappeared
// rows are re-erased under the fence before the failure returns — the wipe
// already cleared the pending markers, so leaving them would strand prior
// leases with no boot gate — and a retry converges. The completed wipe's
// fresh identity is NOT rolled back: the config is gone, so the prior
// identity is meaningless.
func TestFactoryResetFailsWhenKeaLeasesReappear10769(t *testing.T) {
	isolateFactoryResetOwnershipPaths(t)
	isolateFactoryResetIdentityPaths(t)
	isolateHandoffFlag(t)
	if err := os.MkdirAll(filepath.Dir(hostnamePath), 0o700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(hostnamePath, []byte("tenant-fw\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	lease := resetKeaLeaseCurrents[0] + ".completed"
	d := &Daemon{applySem: semaphore.NewWeighted(1)}
	err := d.factoryReset(context.Background(), func() error {
		if err := os.MkdirAll(filepath.Dir(lease), 0o700); err != nil {
			return err
		}
		if err := os.WriteFile(lease, []byte("recreated lease"), 0o600); err != nil {
			return err
		}
		return os.WriteFile(hostnamePath, []byte("xpf\n"), 0o600)
	})
	if err == nil || !strings.Contains(err.Error(), "reappeared") {
		t.Fatalf("recreated lease must fail the reset, got %v", err)
	}
	if _, serr := os.Lstat(lease); !os.IsNotExist(serr) {
		t.Fatalf("reappeared lease must be re-erased before the failure returns: %v", serr)
	}
	if got, _ := os.ReadFile(hostnamePath); string(got) != "xpf\n" {
		t.Fatalf("completed-wipe identity must stand after a verify failure, got %q", got)
	}
	if err := d.factoryReset(context.Background(), fakePendingWipe(t)); err != nil {
		t.Fatalf("retry after a repaired verify failure must converge: %v", err)
	}
}

