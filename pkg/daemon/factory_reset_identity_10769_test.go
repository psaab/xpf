// TestPreSeedCrossesResetFence10769 pins that the direct memfile writer
// serializes on the reset fence: while factoryReset holds it across the wipe,
// a pre-seed must wait rather than land mid-wipe. Deterministic in both
// directions: completion while held is impossible when the lock is crossed,
// and immediate completion without it fails RED.
func TestPreSeedCrossesResetFence10769(t *testing.T) {
	d := leaseSyncTestDaemon(t, filepath.Join(t.TempDir(), "x4.sock"), filepath.Join(t.TempDir(), "x6.sock"), true)
	rec := &preSeedRecorder10769{recordingDHCPApplier9349: &recordingDHCPApplier9349{}}
	d.dhcpServer = rec
	d.sessionSync.SetPeerDHCPLeasesForTesting(4, []dhcpserver.SyncLease{{Family: 4, Address: "10.0.61.7", Remaining: 3600}})
	d.ddnsResetMu.Lock()
	done := make(chan struct{})
	go func() {
		d.preSeedDHCPLeaseMemfile(false)
		close(done)
	}()
	select {
	case <-done:
		d.ddnsResetMu.Unlock()
		t.Fatal("pre-seed completed while the reset fence was held; it must serialize on it")
	case <-time.After(100 * time.Millisecond):
	}
	if got := rec.count(); got != 0 {
		d.ddnsResetMu.Unlock()
		t.Fatalf("pre-seed wrote %d families while fenced, want none", got)
	}
	d.ddnsResetMu.Unlock()
	select {
	case <-done:
	case <-time.After(5 * time.Second):
		t.Fatal("pre-seed did not proceed after the fence released")
	}
	if got := rec.count(); got != 1 {
		t.Fatalf("pre-seed after fence release wrote %d families, want 1", got)
	}
}

