#!/usr/bin/env python3
"""Unit tests for scripts/proto_header_check.py (#16195).

Prove both red directions independently: a wrong generated header,
and a header/go.mod/README drift -- including the case A-Codex required
to be proven independently of the header red (stale .proto leg lives in
the CI regen-diff script, covered by proto_regen_check self-tests there;
here we prove header-vs-go.mod and header-vs-README are distinct signals).
Hermetic: fixture trees in a temp dir, no network/protoc.
"""

from __future__ import annotations

import sys
import textwrap
import unittest
from pathlib import Path
from tempfile import TemporaryDirectory

sys.path.insert(0, str(Path(__file__).resolve().parent / "lib"))
from load_subject import load_subject  # noqa: E402

mod = load_subject(
    "proto_header_check", Path(__file__).with_name("proto_header_check.py"))

PB = """\
// Code generated by protoc-gen-go. DO NOT EDIT.
// versions:
// \tprotoc-gen-go v1.36.11
// \tprotoc        v3.21.12
// source: xpf.proto
"""
GRPC = """\
// Code generated by protoc-gen-go-grpc. DO NOT EDIT.
// versions:
// - protoc-gen-go-grpc v1.6.1
// - protoc             v3.21.12
// source: xpf.proto
"""
README = textwrap.dedent("""\
    - `protoc` v3.21.12
    - `protoc-gen-go` v1.36.11
    - `protoc-gen-go-grpc` v1.6.1
    """)
GOMOD = "module x\n\ngo 1.24.9\n\nrequire google.golang.org/protobuf v1.36.11\n"


def make_tree(root: Path, pb=PB, grpc=GRPC, readme=README, gomod=GOMOD) -> None:
    (root / "pkg/grpcapi/xpfv1").mkdir(parents=True)
    (root / "proto").mkdir()
    (root / "pkg/grpcapi/xpfv1/xpf.pb.go").write_text(pb)
    (root / "pkg/grpcapi/xpfv1/xpf_grpc.pb.go").write_text(grpc)
    (root / "proto/README.md").write_text(readme)
    (root / "go.mod").write_text(gomod)


class CheckTests(unittest.TestCase):
    def run_check(self, **kw) -> list[str]:
        with TemporaryDirectory(dir="/var/worktrees/.cache/tmpdir") as d:
            root = Path(d)
            make_tree(root, **kw)
            return mod.check(root)

    def test_good_tree_passes(self) -> None:
        self.assertEqual(self.run_check(), [])

    def test_wrong_pb_header_version_is_red(self) -> None:
        errs = self.run_check(pb=PB.replace("v1.36.11", "v1.36.10"))
        self.assertTrue(any("protoc-gen-go" in e for e in errs), errs)

    def test_gomod_protobuf_bump_without_regen_is_red(self) -> None:
        errs = self.run_check(gomod=GOMOD.replace("v1.36.11", "v1.36.12"))
        self.assertTrue(any("protobuf" in e for e in errs), errs)

    def test_readme_constant_drift_is_red(self) -> None:
        errs = self.run_check(readme=README.replace("v3.21.12", "v3.21.11"))
        self.assertTrue(any("protoc" in e for e in errs), errs)

    def test_grpc_plugin_stamp_drift_is_red(self) -> None:
        errs = self.run_check(grpc=GRPC.replace("v1.6.1", "v1.6.0"))
        self.assertTrue(any("protoc-gen-go-grpc" in e for e in errs), errs)

    def test_protoc_disagreement_between_headers_is_red(self) -> None:
        errs = self.run_check(grpc=GRPC.replace("v3.21.12", "v3.21.11"))
        self.assertTrue(errs)

    def test_missing_readme_constant_is_red(self) -> None:
        errs = self.run_check(readme=README.replace("- `protoc` v3.21.12\n", ""))
        self.assertTrue(any("protoc" in e for e in errs), errs)

    def test_unstamped_header_is_red(self) -> None:
        errs = self.run_check(pb="// no stamp\n")
        self.assertTrue(errs)


if __name__ == "__main__":
    unittest.main()
